// Generates TypeScript types from the API's OpenAPI document so the web app and API
// share one contract. The schema is exported from the FastAPI app without a running server.
//   node scripts/generate.mjs          write src/openapi.ts
//   node scripts/generate.mjs --check  fail if src/openapi.ts is stale
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = resolve(here, "../../../apps/api");
const outFile = resolve(here, "../src/openapi.ts");

const schemaPath = join(mkdtempSync(join(tmpdir(), "salesiq-openapi-")), "openapi.json");
execFileSync("uv", ["run", "--project", apiDir, "python", "-m", "app.export_openapi", schemaPath], {
  cwd: apiDir,
  stdio: ["ignore", "ignore", "inherit"],
});

const ast = await openapiTS(new URL(`file://${schemaPath.replaceAll("\\", "/")}`));
const output =
  "// AUTO-GENERATED by packages/contracts/scripts/generate.mjs. Do not edit by hand.\n" +
  astToString(ast);

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8").replaceAll("\r\n", "\n");
  if (current !== output) {
    console.error("src/openapi.ts is stale. Run `pnpm contracts:generate`.");
    process.exit(1);
  }
  console.log("contracts up to date");
} else {
  writeFileSync(outFile, output);
  console.log(`wrote ${outFile}`);
}
