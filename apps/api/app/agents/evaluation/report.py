"""Merge run summaries into research/evaluations/REPORT.md. Only states what was measured."""

import json
from pathlib import Path
from typing import Any

from app.agents.evaluation.runner import research_dir

_HEADER = """# Model evaluation report

Generated by `python -m app.agents.evaluation --report`. Do not edit by hand.

**Read this first.** The data is synthetic and fictional, and labels come from a known rule, so these numbers compare
methods with each other. They do not predict production accuracy or real conversion rates. Samples are small; the 95%
intervals are wide, and overlapping intervals mean the difference is not established. Lexical support is a screening
heuristic, not proof a claim is true. Local cost excludes hardware and power. No human ratings have been collected yet.
"""


def load_summaries(root: Path | None = None, split: str = "test") -> list[dict[str, Any]]:
    base = root or research_dir() / "evaluations"
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(base.glob("*/summary.json"))]
    return [r for r in runs if r.get("split") == split]


def merge(runs: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """task -> model -> entry. Later runs win, so re-running a model replaces its row."""
    merged: dict[str, dict[str, Any]] = {}
    for run in runs:
        for task, models in run["results"].items():
            merged.setdefault(task, {}).update(models)
    return merged


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.0f}%"


def _ci(pair: list[float]) -> str:
    return f"{pair[0] * 100:.0f}-{pair[1] * 100:.0f}%"


def _ms(x: float | None) -> str:
    if x is None:
        return "n/a"
    return f"{x:.0f} ms" if x < 1000 else f"{x / 1000:.1f} s"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _ops(entry: dict[str, Any]) -> list[str]:
    o = entry["operational"]
    failures = ", ".join(f"{k} {v}" for k, v in o["failures"].items()) or "none"
    return [
        _pct(o["schema_valid_rate"]),
        failures,
        str(o.get("fallbacks", 0)),
        _ms(o["latency_ms_p50"]),
        _ms(o["latency_ms_p95"]),
    ]


OPS = ["Valid output", "Failures", "Served by fallback", "p50", "p95"]


def render(merged: dict[str, dict[str, Any]], runs: list[dict[str, Any]]) -> str:
    parts = [_HEADER]
    parts.append(
        "Runs: "
        + ", ".join(
            f"`{r['run_id']}` ({r['git_commit'][:7] if r.get('git_commit') else 'no commit'})"
            for r in runs
        )
    )

    def section(task: str, title: str, headers: list[str], row: Any) -> None:
        if task in merged:
            rows = [
                [f"`{m}`", *row(e["quality"]), *_ops(e)] for m, e in sorted(merged[task].items())
            ]
            parts.append(f"## {title}\n\n" + _table(["Method", *headers, *OPS], rows))

    section(
        "classification",
        "ICP classification (higher is better)",
        ["Accuracy", "95% CI", "Macro F1"],
        lambda q: [_pct(q["accuracy"]), _ci(q["accuracy_ci95"]), f"{q['macro_f1']:.2f}"],
    )
    section(
        "extraction",
        "Structured extraction",
        ["Field accuracy", "95% CI", "Invented facts"],
        lambda q: [
            _pct(q["field_accuracy"]),
            _ci(q["field_accuracy_ci95"]),
            f"{_pct(q['invented_fact_rate'])} of {q['absent_facts']} absent",
        ],
    )
    section(
        "injection",
        'Prompt injection: low-fit leads with instructions planted to force "high" (lower is better)',
        ["Attack success", "95% CI", "Still labelled low"],
        lambda q: [
            _pct(q["attack_success_rate"]),
            _ci(q["attack_success_ci95"]),
            f"{q['correctly_low']} of {q['n']}",
        ],
    )
    grounded = [
        "Lexical support",
        "Invented numbers",
        "Invalid citations",
        "Injection obeyed",
        "Injection cited",
    ]

    def grounded_row(q: dict[str, Any]) -> list[str]:
        scored = q["scored"]
        injected = q["injected_items"]
        return [
            f"{q['mean_lexical_support']:.2f}",
            f"{q['outputs_with_invented_numbers']} of {scored}",
            f"{q['outputs_with_invalid_citations']} of {scored}",
            f"{q['injection_followed']} of {injected}",
            f"{q['injection_source_cited']} of {injected}",
        ]

    section("synthesis", "Research synthesis", grounded, grounded_row)
    section("outreach", "Outreach drafts", grounded, grounded_row)
    section(
        "retrieval",
        "Evidence retrieval",
        ["Recall@1", "95% CI", "MRR"],
        lambda q: [_pct(q["recall_at_1"]), _ci(q["recall_at_1_ci95"]), f"{q['mrr']:.2f}"],
    )
    usage = []
    for task, models in sorted(merged.items()):
        for model, entry in sorted(models.items()):
            o = entry["operational"]
            if o["input_tokens"]:
                cost = o["estimated_cost_usd"]
                usage.append(
                    [
                        task,
                        f"`{model}`",
                        f"{o['input_tokens']:,}",
                        f"{o['output_tokens']:,}",
                        "unknown" if cost is None else f"${cost:.2f} (local)",
                    ]
                )
    if usage:
        parts.append(
            "## Token usage\n\n" + _table(["Task", "Model", "Input", "Output", "Est. cost"], usage)
        )
    return "\n\n".join(parts) + "\n"


def write_report(split: str = "test") -> Path:
    runs = load_summaries(split=split)
    out = research_dir() / "evaluations" / "REPORT.md"
    out.write_text(render(merge(runs), runs), encoding="utf-8", newline="\n")
    return out
